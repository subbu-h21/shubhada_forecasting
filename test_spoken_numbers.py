"""Checks for spoken_numbers.py: every way speech-to-text can write a number, in English,
Kannada and Hindi, comes out as plain digits. Offline - no data, no network.
Run: venv\\Scripts\\python.exe test_spoken_numbers.py"""
import sys

sys.stdout.reconfigure(encoding='utf-8')
import spoken_numbers as S  # noqa: E402

fails = []


def check(name, ok, detail=''):
    print(('PASS ' if ok else 'FAIL ') + name + ('' if ok else f'  -> {detail}'))
    if not ok:
        fails.append(name)


def nums(text):
    return [t[1] for t in S.numberize(text) if t[0] == 'n']


# 1. English, every number 0..999
bad = [(n, S.english_words(n), S.numberize(S.english_words(n))) for n in range(1000) if S.numberize(S.english_words(n)) != [('n', str(n))]]
check('English words 0-999 all come out as digits', not bad, bad[:3])
check('"one hundred and twenty" = 120', nums('one hundred and twenty') == ['120'])
check('"fourty" (common misspelling) = 40', nums('fourty') == ['40'])
check('"two thousand five hundred" = 2500', nums('two thousand five hundred') == ['2500'])

# 2. Kannada words (hand-written, not generated by the module's own rules)
KN = {'ಸೊನ್ನೆ': 0, 'ಒಂದು': 1, 'ಎರಡು': 2, 'ಮೂರು': 3, 'ನಾಲ್ಕು': 4, 'ಐದು': 5, 'ಆರು': 6, 'ಏಳು': 7, 'ಎಂಟು': 8, 'ಒಂಬತ್ತು': 9, 'ಹತ್ತು': 10,
      'ಹನ್ನೊಂದು': 11, 'ಹನ್ನೆರಡು': 12, 'ಹದಿಮೂರು': 13, 'ಹದಿನಾಲ್ಕು': 14, 'ಹದಿನೈದು': 15, 'ಹದಿನಾರು': 16, 'ಹದಿನೇಳು': 17, 'ಹದಿನೆಂಟು': 18,
      'ಹತ್ತೊಂಬತ್ತು': 19, 'ಇಪ್ಪತ್ತು': 20, 'ಇಪ್ಪತ್ತೊಂದು': 21, 'ಇಪ್ಪತ್ತೆರಡು': 22, 'ಇಪ್ಪತ್ತಮೂರು': 23, 'ಇಪ್ಪತ್ತೈದು': 25, 'ಮೂವತ್ತು': 30,
      'ಮೂವತ್ತೈದು': 35, 'ನಲವತ್ತು': 40, 'ನಲವತ್ತೆಂಟು': 48, 'ಐವತ್ತು': 50, 'ಐವತ್ತೊಂಬತ್ತು': 59, 'ಅರವತ್ತು': 60, 'ಅರವತ್ತೈದು': 65,
      'ಅರವತ್ತಾರು': 66, 'ಎಪ್ಪತ್ತು': 70, 'ಎಪ್ಪತ್ತೇಳು': 77, 'ಎಂಬತ್ತು': 80, 'ಎಂಬತ್ತಮೂರು': 83, 'ತೊಂಬತ್ತು': 90, 'ತೊಂಬತ್ತೊಂಬತ್ತು': 99,
      'ನೂರು': 100, 'ನೂರೈವತ್ತು': 150, 'ಇನ್ನೂರು': 200, 'ಸಾವಿರ': 1000}
bad = {w: (v, nums(w)) for w, v in KN.items() if nums(w) != [str(v)]}
check(f'{len(KN)} Kannada number words read correctly', not bad, bad)
check('Kannada "ನೂರ ಇಪ್ಪತ್ತೈದು" = 125', nums('ನೂರ ಇಪ್ಪತ್ತೈದು') == ['125'])
check('Kannada "ಮುನ್ನೂರ ಇಪ್ಪತ್ತು" = 320', nums('ಮುನ್ನೂರ ಇಪ್ಪತ್ತು') == ['320'])
check('every number 1-99 has a Kannada word (the table is complete)',
      all(any(v == n and k in ('unit', 'teen', 'tens', 'full') and 0x0C80 <= ord(w[0]) < 0x0D00 for w, (k, v) in S._VOCAB.items()) for n in range(1, 100)))

# 3. Hindi words (Devanagari and Roman)
HI = {'एक': 1, 'दो': 2, 'पांच': 5, 'दस': 10, 'बीस': 20, 'चौबीस': 24, 'सत्ताईस': 27, 'उनचास': 49, 'पैंसठ': 65, 'साठ': 60, 'नब्बे': 90, 'निन्यानवे': 99,
      'ek': 1, 'teen': 3, 'paanch': 5, 'das': 10, 'bees': 20, 'pachchis': 25, 'painsath': 65, 'saath': 60, 'tees': 30, 'chalis': 40, 'pachas': 50, 'nabbe': 90}
bad = {w: (v, nums(w)) for w, v in HI.items() if nums(w) != [str(v)]}
check(f'{len(HI)} Hindi number words read correctly', not bad, bad)
check('Hindi "ek sau pachees" = 125', nums('ek sau pachees') == ['125'])
check('Hindi "एक सौ पचीस"-style: दो सौ = 200', nums('दो सौ') == ['200'])
check('every number 1-99 has a Hindi word', all(any(v == n and k in ('unit', 'teen', 'tens', 'full') and 0x0900 <= ord(w[0]) < 0x0980 for w, (k, v) in S._VOCAB.items()) for n in range(1, 100)))

# 4. digits in other scripts
check('Kannada digits ೬೫.೬೦ = 65.60', nums('೬೫.೬೦') == ['65.60'])
check('Devanagari digits ६५.६० = 65.60', nums('६५.६०') == ['65.60'])
check('Arabic-Indic digits ٦٥ = 65', nums('٦٥') == ['65'])

# 5. every way to say 65.60
for spoken in ['65.60', 'sixty five point six zero', 'sixty five point sixty', 'sixty-five point 6 0', '65 point 6 0', '65 point six zero',
               'ಅರವತ್ತೈದು ಪಾಯಿಂಟ್ ಆರು ಸೊನ್ನೆ', 'ಅರವತ್ತೈದು ಪಾಯಿಂಟ್ ಅರವತ್ತು', 'पैंसठ पॉइंट छह शून्य', 'painsath point chhe sifar',
               'ಸಿಕ್ಸ್ಟಿ ಫೈವ್ ಪಾಯಿಂಟ್ ಸಿಕ್ಸ್ ಝೀರೋ', '65 dot 60', 'sixty five decimal six zero']:
    check(f'"{spoken}" = 65.60', nums(spoken) == ['65.60'], nums(spoken))
check('"point twenty two" = .22 and "point fifteen" = .15', nums('sixty one point twenty two') == ['61.22'] and nums('ten point fifteen') == ['10.15'])
check('"point six five" = .65 (digit by digit)', nums('sixty one point six five') == ['61.65'])
check('"point five" after a number is .5 (tenths)', nums('sixty five point five') == ['65.5'])
check('"point zero five" is .05 (paise 05)', nums('sixty five point zero five') == ['65.05'])
check('"zero point five" = 0.5', nums('zero point five') == ['0.5'])
check('thousands comma before decimals: 1,250.00', nums('1,250.00') == ['1250.00'])

# 6. numbers that follow each other stay separate
check('"sixty five sixty thirty" = 65, 60, 30', nums('sixty five sixty thirty') == ['65', '60', '30'])
check('"65 60 30" = 65, 60, 30', nums('65 60 30') == ['65', '60', '30'])
check('"sixty five six" = 65, 6 (not 71)', nums('sixty five six') == ['65', '6'])
check('"twenty thirty" = 20, 30', nums('twenty thirty') == ['20', '30'])
check('Kannada "ಅರವತ್ತೈದು ಅರವತ್ತು ಮೂವತ್ತು" = 65, 60, 30', nums('ಅರವತ್ತೈದು ಅರವತ್ತು ಮೂವತ್ತು') == ['65', '60', '30'])

# 7. commas and words are kept, other words untouched
t = S.numberize('eco 65.60, 30 tablets')
check('words, commas and numbers come out in order', t == [('w', 'eco'), ('n', '65.60'), (',',), ('n', '30'), ('w', 'tablets')], t)
check('zero-width joiners inside Kannada words do not break them', nums('ಅರವತ್ತೈ‌ದು') == ['65'])
check('a lone "point" with nothing after it is just a word', S.numberize('point') == [('w', 'point')])
check('words_to_digits writes it back', S.words_to_digits('eco sixty five point six zero, thirty') == 'eco 65.60, 30')

print('\nALL PASSED' if not fails else f'\n{len(fails)} FAILED: {fails}')
sys.exit(1 if fails else 0)
